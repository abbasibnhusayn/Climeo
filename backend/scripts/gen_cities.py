def slugify(name, cc):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return f"{s}-{cc}"

seen = set()
entries = []
for name, country, cc, lat, lon in CITIES:
    slug = slugify(name, cc)
    if slug in seen:
        continue
    seen.add(slug)
    entries.append({"slug": slug, "name": name, "country": country, "latitude": lat, "longitude": lon})

